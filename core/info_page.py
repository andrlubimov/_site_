from pathlib import Path
from types import SimpleNamespace

from django.conf import settings

DOCS_DIR = Path(settings.BASE_DIR) / 'static' / 'documents'


def _size_label(path):
    try:
        size = (DOCS_DIR / path).stat().st_size
    except OSError:
        return ''
    if size >= 1024 * 1024:
        return f'{size / 1024 / 1024:.1f} МБ'.replace('.', ',')
    return f'{max(size // 1024, 1)} КБ'


def doc(title, path, signed=False):
    """Документ: название, путь в static/, размер; signed — рядом лежит файл электронной подписи (.sig)"""
    return SimpleNamespace(
        title=title, path=f'documents/{path}', size=_size_label(path),
        sig_path=f'documents/{path}.sig' if signed else '',
    )


